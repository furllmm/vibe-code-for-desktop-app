"""Structural project index used by the context engine and the index inspector.

The indexer extracts symbols and raw import/include statements per file, then
resolves those statements into a workspace-local file dependency graph. Per-file
results are cached under ``.vibe-code/index/`` keyed by size and mtime so only
changed files are re-parsed on the next build.
"""
from __future__ import annotations

import ast
import json
import os
import subprocess
import tempfile
import time
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from .extractors import extract_c_family, extract_go, extract_rust

CACHE_VERSION = 2
CACHE_RELATIVE = Path(".vibe-code") / "index" / "index.json"

IGNORED_DIRS = frozenset({
    ".git", ".hg", ".svn", ".venv", "venv", "env", "node_modules", "__pycache__",
    "dist", "build", "target", "out", "bin", "obj", ".vibe-code", ".mypy_cache",
    ".pytest_cache", ".ruff_cache", ".tox", ".nox", ".idea", ".vscode", ".gradle",
    ".next", ".nuxt", "coverage", "htmlcov", ".eggs", "site-packages", "vendor",
})
GENERATED_SUFFIXES = ("_pb2.py", "_pb2_grpc.py", ".min.js", ".min.css", ".g.cs", ".designer.cs")
GENERATED_MARKERS = ("@generated", "do not edit", "auto-generated", "autogenerated")

LANGUAGES = {
    ".py": "python",
    ".rs": "rust",
    ".c": "c",
    ".h": "c",
    ".cpp": "cpp",
    ".cc": "cpp",
    ".cxx": "cpp",
    ".hpp": "cpp",
    ".hh": "cpp",
    ".hxx": "cpp",
    ".cs": "csharp",
    ".go": "go",
    ".java": "java",
    ".kt": "kotlin",
}

MAX_FILES = 20_000
MAX_FILE_BYTES = 512_000
MAX_SCAN_BYTES = 256 * 1024 * 1024


@dataclass(frozen=True)
class Symbol:
    name: str
    kind: str
    line: int
    end_line: int | None = None
    parent: str | None = None

    @property
    def qualified_name(self) -> str:
        return f"{self.parent}.{self.name}" if self.parent else self.name


@dataclass(frozen=True)
class FileIndex:
    path: Path
    language: str
    symbols: tuple[Symbol, ...] = field(default_factory=tuple)
    imports: tuple[str, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class IndexStats:
    total_files: int = 0
    reindexed: int = 0
    reused: int = 0
    removed: int = 0
    skipped_generated: int = 0
    duration_ms: float = 0.0

    def summary(self) -> str:
        return (
            f"{self.total_files} files indexed ({self.reindexed} parsed, "
            f"{self.reused} cached, {self.removed} removed, "
            f"{self.skipped_generated} generated skipped) in {self.duration_ms:.0f} ms"
        )


@dataclass
class ProjectIndex:
    """Index of a workspace: files, symbols, dependency graph and change history."""

    root: Path
    files: dict[str, FileIndex]
    dependencies: dict[str, tuple[str, ...]]
    dependents: dict[str, tuple[str, ...]]
    change_counts: dict[str, int] = field(default_factory=dict)
    stats: IndexStats = field(default_factory=IndexStats)

    def relative(self, path: Path) -> str | None:
        try:
            return path.expanduser().resolve().relative_to(self.root).as_posix()
        except (OSError, ValueError):
            return None

    def get(self, path: Path) -> FileIndex | None:
        relative = self.relative(path)
        return self.files.get(relative) if relative is not None else None

    def find_symbols(self, query: str) -> list[tuple[str, Symbol]]:
        needle = query.casefold()
        return [
            (relative, symbol)
            for relative, item in sorted(self.files.items())
            for symbol in item.symbols
            if needle in symbol.name.casefold()
        ]

    def related(self, relative: str, depth: int = 1) -> set[str]:
        seen = {relative}
        frontier = {relative}
        for _ in range(max(0, depth)):
            nxt: set[str] = set()
            for node in frontier:
                nxt.update(self.dependencies.get(node, ()))
                nxt.update(self.dependents.get(node, ()))
            frontier = nxt - seen
            seen |= frontier
        seen.discard(relative)
        return seen

    def project_map(self, max_chars: int = 6000) -> str:
        """Compact, bounded outline of files, top-level symbols and local dependencies."""
        lines: list[str] = []
        used = 0
        for relative, item in sorted(self.files.items()):
            top = [s.name for s in item.symbols if s.parent is None][:12]
            deps = list(self.dependencies.get(relative, ()))[:6]
            line = f"{relative} [{item.language}]"
            if top:
                line += f" symbols: {', '.join(top)}"
            if deps:
                line += f" -> {', '.join(deps)}"
            if used + len(line) + 1 > max_chars:
                lines.append(f"... ({len(self.files) - len(lines)} more files)")
                break
            lines.append(line)
            used += len(line) + 1
        return "\n".join(lines)


class ProjectIndexer:
    """Build structural indexes with optional incremental on-disk caching."""

    def __init__(self, *, history_limit: int = 200) -> None:
        self.history_limit = history_limit

    # Backwards-compatible API: a plain tuple of per-file indexes, no cache writes.
    def build(self, root: Path) -> tuple[FileIndex, ...]:
        index = self.build_index(root, use_cache=False, history=False)
        return tuple(index.files[key] for key in sorted(index.files))

    def build_index(
        self, root: Path, *, use_cache: bool = True, history: bool = True
    ) -> ProjectIndex:
        started = time.monotonic()
        root = root.expanduser().resolve()
        cache = self._load_cache(root) if use_cache else {}
        files: dict[str, FileIndex] = {}
        new_cache: dict[str, dict] = {}
        reused = reindexed = skipped_generated = 0

        for path, relative, stat in self._discover(root):
            language = LANGUAGES[path.suffix.lower()]
            cached = cache.get(relative)
            if (
                cached is not None
                and cached.get("mtime_ns") == stat.st_mtime_ns
                and cached.get("size") == stat.st_size
                and cached.get("language") == language
            ):
                if cached.get("generated"):
                    skipped_generated += 1
                    new_cache[relative] = cached
                    continue
                item = self._from_cache(path, cached)
                if item is not None:
                    files[relative] = item
                    new_cache[relative] = cached
                    reused += 1
                    continue
            text = self._read(path)
            entry = {"mtime_ns": stat.st_mtime_ns, "size": stat.st_size, "language": language}
            if text is None:
                continue
            if self._is_generated(path, text):
                skipped_generated += 1
                new_cache[relative] = {**entry, "generated": True}
                continue
            item = self._index_text(path, language, text)
            files[relative] = item
            new_cache[relative] = {**entry, **self._to_cache(item)}
            reindexed += 1

        removed = len(set(cache) - set(new_cache))
        dependencies = self._resolve_dependencies(root, files)
        dependents: dict[str, list[str]] = {}
        for source, targets in dependencies.items():
            for target in targets:
                dependents.setdefault(target, []).append(source)
        if use_cache and (reindexed or removed or set(cache) != set(new_cache)):
            self._save_cache(root, new_cache)
        stats = IndexStats(
            total_files=len(files),
            reindexed=reindexed,
            reused=reused,
            removed=removed,
            skipped_generated=skipped_generated,
            duration_ms=(time.monotonic() - started) * 1000,
        )
        return ProjectIndex(
            root=root,
            files=files,
            dependencies=dependencies,
            dependents={k: tuple(sorted(v)) for k, v in dependents.items()},
            change_counts=self._change_counts(root) if history else {},
            stats=stats,
        )

    # ------------------------------------------------------------------ discovery
    def _discover(self, root: Path):
        count = 0
        scanned = 0
        for current, dirnames, filenames in os.walk(root, followlinks=False):
            dirnames[:] = sorted(
                d for d in dirnames
                if d not in IGNORED_DIRS
                and not d.endswith(".egg-info")
                and not d.startswith("cmake-build-")
                and not os.path.islink(os.path.join(current, d))
            )
            for name in sorted(filenames):
                path = Path(current) / name
                if path.suffix.lower() not in LANGUAGES:
                    continue
                try:
                    if path.is_symlink():
                        continue
                    stat = path.stat()
                except OSError:
                    continue
                if stat.st_size > MAX_FILE_BYTES:
                    continue
                if count >= MAX_FILES or scanned + stat.st_size > MAX_SCAN_BYTES:
                    return
                count += 1
                scanned += stat.st_size
                yield path, path.relative_to(root).as_posix(), stat

    @staticmethod
    def _read(path: Path) -> str | None:
        try:
            return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return None

    @staticmethod
    def _is_generated(path: Path, text: str) -> bool:
        if path.name.lower().endswith(GENERATED_SUFFIXES):
            return True
        head = text[:600].lower()
        return any(marker in head for marker in GENERATED_MARKERS)

    # ------------------------------------------------------------------ extraction
    def _index_text(self, path: Path, language: str, text: str) -> FileIndex:
        if language == "python":
            return self._index_python(path, text)
        if language == "rust":
            symbols, imports = extract_rust(text)
        elif language in {"c", "cpp"}:
            symbols, imports = extract_c_family(text)
        elif language == "go":
            symbols, imports = extract_go(text)
        else:
            return FileIndex(path, language)
        return FileIndex(path, language, tuple(Symbol(*s) for s in symbols), tuple(imports))

    def _index_python(self, path: Path, text: str | None = None) -> FileIndex:
        if text is None:
            text = self._read(path) or ""
        try:
            tree = ast.parse(text)
        except (SyntaxError, ValueError):
            return FileIndex(path, "python")
        symbols: list[Symbol] = []
        imports: list[str] = []

        def visit(nodes, parent: str | None, parent_is_class: bool) -> None:
            for node in nodes:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    kind = "method" if parent_is_class else "function"
                    symbols.append(Symbol(node.name, kind, node.lineno, node.end_lineno, parent))
                    visit(node.body, node.name, False)
                elif isinstance(node, ast.ClassDef):
                    symbols.append(Symbol(node.name, "class", node.lineno, node.end_lineno, parent))
                    visit(node.body, node.name, True)
                elif isinstance(node, ast.Import):
                    imports.extend(alias.name for alias in node.names)
                elif isinstance(node, ast.ImportFrom):
                    prefix = "." * node.level
                    if node.module:
                        imports.append(prefix + node.module)
                        if node.level:
                            imports.extend(
                                f"{prefix}{node.module}.{alias.name}" for alias in node.names
                            )
                    else:
                        imports.extend(prefix + alias.name for alias in node.names)
                else:
                    for child_field in ("body", "orelse", "finalbody", "handlers"):
                        children = getattr(node, child_field, None)
                        if isinstance(children, list):
                            visit(children, parent, parent_is_class)

        visit(tree.body, None, False)
        symbols.sort(key=lambda item: (item.line, item.name))
        return FileIndex(path, "python", tuple(symbols), tuple(sorted(set(imports))))

    # ------------------------------------------------------------------ dependency graph
    def _resolve_dependencies(
        self, root: Path, files: dict[str, FileIndex]
    ) -> dict[str, tuple[str, ...]]:
        known = set(files)
        by_name: dict[str, list[str]] = {}
        for relative in known:
            by_name.setdefault(PurePosixPath(relative).name, []).append(relative)
        python_roots = [""] + [p for p in ("src", "lib") if any(k.startswith(p + "/") for k in known)]
        result: dict[str, tuple[str, ...]] = {}
        for relative, item in files.items():
            targets: set[str] = set()
            for raw in item.imports:
                if item.language == "python":
                    resolved = self._resolve_python(relative, raw, known, python_roots)
                elif item.language == "rust":
                    resolved = self._resolve_rust(relative, raw, known)
                elif item.language in {"c", "cpp"}:
                    resolved = self._resolve_include(relative, raw, known, by_name)
                else:
                    resolved = None
                if resolved and resolved != relative:
                    targets.add(resolved)
            if targets:
                result[relative] = tuple(sorted(targets))
        return result

    @staticmethod
    def _python_candidates(base: PurePosixPath, parts: list[str]) -> list[str]:
        out: list[str] = []
        for n in range(len(parts), 0, -1):
            stem = base.joinpath(*parts[:n])
            out.append(f"{stem}.py")
            out.append(f"{stem}/__init__.py")
        return [c.lstrip("./") if c.startswith("./") else c for c in out]

    def _resolve_python(
        self, relative: str, raw: str, known: set[str], roots: list[str]
    ) -> str | None:
        level = len(raw) - len(raw.lstrip("."))
        module = raw[level:]
        parts = [p for p in module.split(".") if p]
        if level:
            base = PurePosixPath(relative).parent
            for _ in range(level - 1):
                base = base.parent
            if not parts:
                candidate = f"{base}/__init__.py" if str(base) != "." else "__init__.py"
                return candidate if candidate in known else None
            for candidate in self._python_candidates(base, parts):
                candidate = candidate[2:] if candidate.startswith("./") else candidate
                if candidate in known:
                    return candidate
            return None
        for root in roots:
            base = PurePosixPath(root) if root else PurePosixPath(".")
            for candidate in self._python_candidates(base, parts):
                candidate = candidate[2:] if candidate.startswith("./") else candidate
                if candidate in known:
                    return candidate
        return None

    @staticmethod
    def _resolve_rust(relative: str, raw: str, known: set[str]) -> str | None:
        path = PurePosixPath(relative)
        kind, _, value = raw.partition(":")
        if kind == "mod":
            if path.name in {"main.rs", "lib.rs", "mod.rs"}:
                base = path.parent
            else:
                base = path.parent / path.stem
            for candidate in (base / f"{value}.rs", base / value / "mod.rs"):
                if candidate.as_posix() in known:
                    return candidate.as_posix()
            return None
        if kind == "use":
            segments = [s for s in value.split("::") if s]
            if not segments or segments[0] not in {"crate", "self", "super"}:
                return None
            if segments[0] == "crate":
                parents = list(path.parents)
                base = next((p for p in parents if p.name == "src"), path.parent)
            elif segments[0] == "self":
                base = path.parent if path.name in {"main.rs", "lib.rs", "mod.rs"} else path.parent / path.stem
            else:
                base = path.parent.parent if path.name == "mod.rs" else path.parent
            rest = segments[1:]
            for n in range(len(rest), 0, -1):
                stem = base.joinpath(*rest[:n])
                for candidate in (f"{stem}.rs", f"{stem}/mod.rs"):
                    if candidate in known:
                        return candidate
        return None

    @staticmethod
    def _resolve_include(
        relative: str, raw: str, known: set[str], by_name: dict[str, list[str]]
    ) -> str | None:
        if not raw.startswith('"'):
            return None
        target = raw.strip('"')
        here = PurePosixPath(relative).parent
        candidates = [here / target, PurePosixPath(target), PurePosixPath("include") / target,
                      PurePosixPath("src") / target]
        for candidate in candidates:
            normalized = os.path.normpath(candidate.as_posix()).replace(os.sep, "/")
            if normalized in known:
                return normalized
        matches = [k for k in by_name.get(PurePosixPath(target).name, []) if k.endswith("/" + target) or k == target]
        return matches[0] if len(matches) == 1 else None

    # ------------------------------------------------------------------ history
    def _change_counts(self, root: Path) -> dict[str, int]:
        try:
            result = subprocess.run(
                ["git", "log", f"-n{self.history_limit}", "--name-only",
                 "--pretty=format:", "--no-renames"],
                cwd=root, capture_output=True, text=True, timeout=3, check=False,
                stdin=subprocess.DEVNULL,
            )
        except (OSError, subprocess.SubprocessError):
            return {}
        if result.returncode != 0:
            return {}
        counts = Counter(line.strip() for line in result.stdout.splitlines() if line.strip())
        return dict(counts)

    # ------------------------------------------------------------------ cache
    @staticmethod
    def _to_cache(item: FileIndex) -> dict:
        return {
            "symbols": [[s.name, s.kind, s.line, s.end_line, s.parent] for s in item.symbols],
            "imports": list(item.imports),
        }

    @staticmethod
    def _from_cache(path: Path, entry: dict) -> FileIndex | None:
        try:
            symbols = tuple(
                Symbol(str(n), str(k), int(line), None if e is None else int(e),
                       None if p is None else str(p))
                for n, k, line, e, p in entry.get("symbols", [])
            )
            imports = tuple(str(value) for value in entry.get("imports", []))
            return FileIndex(path, str(entry["language"]), symbols, imports)
        except (KeyError, TypeError, ValueError):
            return None

    @staticmethod
    def _load_cache(root: Path) -> dict[str, dict]:
        path = root / CACHE_RELATIVE
        try:
            if path.is_symlink() or not path.is_file():
                return {}
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, ValueError):
            return {}
        if not isinstance(data, dict) or data.get("version") != CACHE_VERSION:
            return {}
        files = data.get("files")
        if not isinstance(files, dict):
            return {}
        return {k: v for k, v in files.items() if isinstance(k, str) and isinstance(v, dict)}

    @staticmethod
    def _save_cache(root: Path, files: dict[str, dict]) -> None:
        target = root / CACHE_RELATIVE
        try:
            for parent in (root / ".vibe-code", target.parent):
                if parent.is_symlink():
                    return
            target.parent.mkdir(parents=True, exist_ok=True)
            fd, temp = tempfile.mkstemp(prefix=".index-", dir=target.parent)
            try:
                with os.fdopen(fd, "w", encoding="utf-8") as handle:
                    json.dump({"version": CACHE_VERSION, "files": files}, handle)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temp, target)
            except BaseException:
                Path(temp).unlink(missing_ok=True)
                raise
        except OSError:
            return
